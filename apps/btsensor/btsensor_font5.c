bool btsensor_font5_glyph(char c, uint8_t rows[5])
{
  if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
  for (size_t i = 0; i < sizeof(g_glyphs) / sizeof(g_glyphs[0]); i++)
    if (g_glyphs[i].c == c)
      {
        for (unsigned r = 0; r < 5; r++) rows[r] = g_glyphs[i].rows[r];
        return true;
      }
  return false;
}
